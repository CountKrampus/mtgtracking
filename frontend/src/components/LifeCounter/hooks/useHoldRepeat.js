import { useCallback, useEffect, useRef } from 'react';

/**
 * Hold-to-repeat behavior for buttons.
 *
 * Fires immediately on pointer down, then repeats on an interval while the
 * pointer stays down. The synthetic `click` that follows a pointer sequence
 * is swallowed so the action never double-fires; keyboard activation
 * (Enter/Space, which produces a click with no preceding pointerdown) still
 * fires normally.
 *
 * @param {Function} onFire - called for each fire (first tap + every repeat)
 * @param {Object} [options]
 * @param {number} [options.initialDelay=400] - ms held before repeats start
 * @param {number} [options.repeatInterval=120] - ms between repeats
 * @returns {{onPointerDown, onPointerUp, onPointerLeave, onPointerCancel, onClick}}
 */
function useHoldRepeat(onFire, { initialDelay = 400, repeatInterval = 120 } = {}) {
  const onFireRef = useRef(onFire);
  onFireRef.current = onFire;

  const timeoutRef = useRef(null);
  const intervalRef = useRef(null);
  const lastPointerDownAtRef = useRef(0);

  const stop = useCallback(() => {
    if (timeoutRef.current !== null) {
      clearTimeout(timeoutRef.current);
      timeoutRef.current = null;
    }
    if (intervalRef.current !== null) {
      clearInterval(intervalRef.current);
      intervalRef.current = null;
    }
  }, []);

  const handlePointerDown = useCallback((e) => {
    // Left button only for mouse; touch/pen report button 0 or undefined
    if (e.button != null && e.button !== 0) return;
    lastPointerDownAtRef.current = Date.now();
    stop();
    onFireRef.current();
    timeoutRef.current = setTimeout(() => {
      timeoutRef.current = null;
      intervalRef.current = setInterval(() => onFireRef.current(), repeatInterval);
    }, initialDelay);
  }, [initialDelay, repeatInterval, stop]);

  const handleClick = useCallback(() => {
    // Swallow the click generated by a pointer sequence we already handled
    if (Date.now() - lastPointerDownAtRef.current < 600) return;
    onFireRef.current();
  }, []);

  // Global safety net: pointerup/cancel/blur can land outside the button
  // (drag off, tab away), which would otherwise leave the interval running.
  useEffect(() => {
    const end = () => stop();
    window.addEventListener('pointerup', end);
    window.addEventListener('pointercancel', end);
    window.addEventListener('blur', end);
    return () => {
      window.removeEventListener('pointerup', end);
      window.removeEventListener('pointercancel', end);
      window.removeEventListener('blur', end);
      stop();
    };
  }, [stop]);

  return {
    onPointerDown: handlePointerDown,
    onPointerUp: stop,
    onPointerLeave: stop,
    onPointerCancel: stop,
    onClick: handleClick
  };
}

export default useHoldRepeat;
